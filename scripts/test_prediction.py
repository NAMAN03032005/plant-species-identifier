"""
LeafScan - Standalone CLI Prediction Test Script (Step 4)
==========================================================
Usage:
  python scripts/test_prediction.py <path_to_leaf_image>

Example:
  python scripts/test_prediction.py dataset/test/Apple___healthy/sample_001.jpg

This script loads the REAL trained MobileNetV2 Keras model (model/leafscan_mobilenetv2.keras)
and evaluates a real leaf image, returning the predicted species and confidence percentage.
"""

import os
import sys
import json
import numpy as np
from PIL import Image

# Suppress TensorFlow verbose logging
os.environ['TF_CPP_MIN_LOG_LEVEL'] = '2'
import tensorflow as tf

# Paths
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_PATH = os.path.join(BASE_DIR, 'model', 'leafscan_mobilenetv2.keras')
CLASS_NAMES_PATH = os.path.join(BASE_DIR, 'model', 'class_names.json')


def load_model_and_classes():
    """Load trained Keras model and species class names."""
    if not os.path.exists(MODEL_PATH):
        print(f"[Error] Trained model weights file not found at: {MODEL_PATH}")
        print("Please run 'python scripts/train_model.py' first to train the model.")
        sys.exit(1)

    if not os.path.exists(CLASS_NAMES_PATH):
        print(f"[Error] Class names JSON file not found at: {CLASS_NAMES_PATH}")
        sys.exit(1)

    print("[Info] Loading trained MobileNetV2 Keras model...")
    model = tf.keras.models.load_model(MODEL_PATH)
    
    with open(CLASS_NAMES_PATH, 'r') as f:
        class_names = json.load(f)

    return model, class_names


def predict_leaf(image_path):
    """
    Preprocess input image, run model inference, and output prediction scores.
    """
    if not os.path.exists(image_path):
        print(f"[Error] Input image file does not exist: {image_path}")
        sys.exit(1)

    model, class_names = load_model_and_classes()

    # Load and preprocess image
    try:
        img = Image.open(image_path).convert('RGB')
        img_resized = img.resize((224, 224))
        img_array = np.array(img_resized, dtype=np.float32)
        
        # Expand dimensions to batch format (1, 224, 224, 3)
        img_batch = np.expand_dims(img_array, axis=0)

        # Apply MobileNetV2 recommended input scaling
        # (Note: preprocess_input is integrated inside model, or applied here)
        preds = model.predict(img_batch, verbose=0)[0]

        top_idx = int(np.argmax(preds))
        top_species = class_names[top_idx]
        top_confidence = float(preds[top_idx]) * 100

        print("\n" + "=" * 65)
        print("         LeafScan - AI Leaf Species Prediction Output")
        print("=" * 65)
        print(f"Image File Path : {image_path}")
        print("-" * 65)
        print(f"Predicted species: {top_species}")
        print(f"Confidence       : {top_confidence:.2f}%")
        print("-" * 65)

        # Top 3 Candidates
        top3_indices = np.argsort(preds)[::-1][:3]
        print("Top 3 Model Probabilities:")
        for rank, idx in enumerate(top3_indices, 1):
            name = class_names[idx]
            conf = float(preds[idx]) * 100
            print(f"  {rank}. {name:<30} : {conf:.2f}%")

        print("=" * 65)
        print("Note: Prediction is generated by real fine-tuned MobileNetV2 model weights.")
        print("The model can only recognize species among its 10 trained classes.")
        print("=" * 65)

    except Exception as e:
        print(f"[Error] Failed to process image or run inference: {e}")
        sys.exit(1)


if __name__ == '__main__':
    if len(sys.argv) < 2:
        print("Usage: python scripts/test_prediction.py <path_to_leaf_image>")
        print("Example: python scripts/test_prediction.py dataset/test/Apple___healthy/Apple___healthy_sample_035.jpg")
        sys.exit(1)

    image_file = sys.argv[1]
    predict_leaf(image_file)
